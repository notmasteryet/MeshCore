#!/usr/bin/env python3
"""Minimal TTF/WOFF -> LVGL 8 font converter (4 bpp, uncompressed, no kerning).

Stands in for lv_font_conv (Node) so the CYD UI fonts can be regenerated with
Python + Pillow only:

    python mkfont.py <font.ttf> <size_px> <c_name> <ranges> <out.c>

<ranges>: comma-separated codepoints or ranges, hex or decimal, e.g.
"0x20-0x7E,0xA0-0xFF,0x400-0x45F,0x2026".
"""
import sys
from PIL import Image, ImageDraw, ImageFont


def parse_ranges(spec):
    cps = set()
    for part in spec.split(','):
        part = part.strip()
        if not part:
            continue
        if '-' in part[1:]:
            a, b = part.split('-', 1) if not part.startswith('-') else part[1:].split('-', 1)
            cps.update(range(int(a, 0), int(b, 0) + 1))
        else:
            cps.add(int(part, 0))
    return sorted(cps)


def has_glyph(font_path, cps):
    from fontTools.ttLib import TTFont
    cmap = TTFont(font_path).getBestCmap()
    return [c for c in cps if c in cmap]


def main():
    path, size, name, spec, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4], sys.argv[5]
    font = ImageFont.truetype(path, size)
    asc, desc = font.getmetrics()
    cps = has_glyph(path, parse_ranges(spec))

    bitmap = bytearray()
    glyphs = [(0, 0, 0, 0, 0, 0)]  # id 0 reserved
    for cp in cps:
        ch = chr(cp)
        adv = round(font.getlength(ch) * 16)
        l, t, r, b = font.getbbox(ch, anchor='ls')
        w, h = max(0, r - l), max(0, b - t)
        idx = len(bitmap)
        if w and h:
            img = Image.new('L', (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor='ls')
            px = img.tobytes()
            nib = [v >> 4 for v in px]
            if len(nib) % 2:
                nib.append(0)
            bitmap.extend((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
        glyphs.append((idx, adv, w, h, l, -b))

    # group consecutive codepoints into FORMAT0_TINY ranges
    ranges = []
    start = prev = None
    gid = 1
    for i, cp in enumerate(cps):
        if start is None:
            start, prev, first = cp, cp, gid + i
        elif cp == prev + 1:
            prev = cp
        else:
            ranges.append((start, prev - start + 1, first))
            start, prev, first = cp, cp, gid + i
    if start is not None:
        ranges.append((start, prev - start + 1, first))

    o = []
    o.append('/* Generated by tools/cyd_ui/mkfont.py from %s, %dpx, 4bpp */' % (path.split('/')[-1], size))
    o.append('#include "lvgl.h"\n')
    o.append('static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {')
    for i in range(0, len(bitmap), 24):
        o.append('    ' + ', '.join('0x%02x' % v for v in bitmap[i:i + 24]) + ',')
    if not bitmap:
        o.append('    0x00,')
    o.append('};\n')
    o.append('static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {')
    for g in glyphs:
        o.append('    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d},' % g)
    o.append('};\n')
    o.append('static const lv_font_fmt_txt_cmap_t cmaps[] = {')
    for s, n, g in ranges:
        o.append('    {.range_start = %d, .range_length = %d, .glyph_id_start = %d, .unicode_list = NULL, '
                 '.glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},' % (s, n, g))
    o.append('};\n')
    o.append('static lv_font_fmt_txt_glyph_cache_t cache;')
    o.append('static const lv_font_fmt_txt_dsc_t font_dsc = {')
    o.append('    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL,')
    o.append('    .kern_scale = 0, .cmap_num = %d, .bpp = 4, .kern_classes = 0, .bitmap_format = 0, .cache = &cache' % len(ranges))
    o.append('};\n')
    o.append('const lv_font_t %s = {' % name)
    o.append('    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,')
    o.append('    .line_height = %d, .base_line = %d, .subpx = LV_FONT_SUBPX_NONE,' % (asc + desc, desc))
    o.append('    .underline_position = -1, .underline_thickness = 1, .dsc = &font_dsc, .fallback = NULL, .user_data = NULL')
    o.append('};')
    open(out, 'w').write('\n'.join(o) + '\n')
    print('%s: %d glyphs, %d ranges, %d bytes bitmap' % (name, len(cps), len(ranges), len(bitmap)))


if __name__ == '__main__':
    main()
